#!/usr/bin/env python3
"""Generates the Android app icon and splash screens: a dark hangboard with three pockets
and a blue pull curve (ramp, hold, release) under it, on a light background. Writes into
android/app/src/main/res:

  drawable/ic_launcher_foreground.xml   vector foreground of the adaptive icon (API 26+)
  mipmap-*/ic_launcher*.png             PNG icons for older Android versions
  drawable*/splash.png                  splash screens (icon on the dark app background)

Run after changing the design:  python3 tools/make_icons.py   (needs Pillow)
"""
import os

from PIL import Image, ImageDraw

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

LIGHT = "#F8FAFC"  # icon background
INK = "#1E293B"  # hangboard
BLUE = "#2563EB"  # pull curve (the app's accent)
DARK = "#111418"  # app background (dark theme)

# Shapes in the 108×108 adaptive-icon viewport (safe zone: the central 66×66).
BOARD = (25, 28, 83, 42, 5)  # hangboard: x0, y0, x1, y1, corner radius
POCKETS = [(31, 33, 45, 38), (48, 33, 60, 38), (63, 33, 77, 38)]  # radius = half the height
# The pull: rest, ramp up, hold (a little wobble), let go, rest. Lines and cubic Béziers.
CURVE = [
    ("M", (25, 80)),
    ("L", (32, 80)),
    ("C", (36, 80), (37, 58), (43, 58)),
    ("L", (52, 59)),
    ("L", (60, 57.5)),
    ("L", (67, 59)),
    ("C", (71, 59), (72, 80), (76, 80)),
    ("L", (83, 80)),
]
CURVE_W = 5


def rounded_path(x0, y0, x1, y1, r):
    return (f"M{x0 + r},{y0} H{x1 - r} A{r},{r} 0 0 1 {x1},{y0 + r} V{y1 - r} A{r},{r} 0 0 1 {x1 - r},{y1} "
            f"H{x0 + r} A{r},{r} 0 0 1 {x0},{y1 - r} V{y0 + r} A{r},{r} 0 0 1 {x0 + r},{y0} Z")


def curve_path():
    fmt = lambda p: f"{p[0]},{p[1]}"  # noqa: E731
    return " ".join(cmd + " ".join(fmt(p) for p in pts) for cmd, *pts in CURVE)


def curve_points(steps=24):
    """The curve as a polyline (Béziers sampled), for the PNG icons."""
    pts = []
    for cmd, *ps in CURVE:
        if cmd in "ML":
            pts.append(ps[0])
            continue
        (x0, y0), (x1, y1), (x2, y2), (x3, y3) = pts[-1], *ps
        for i in range(1, steps + 1):
            t = i / steps
            a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t**3
            pts.append((a * x0 + b * x1 + c * x2 + d * x3, a * y0 + b * y1 + c * y2 + d * y3))
    return pts


POCKET_PATHS = "\n".join(
    f'    <path android:fillColor="{LIGHT}" android:pathData="{rounded_path(*p, (p[3] - p[1]) / 2)}" />' for p in POCKETS
)
VECTOR = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{INK}" android:pathData="{rounded_path(*BOARD)}" />
{POCKET_PATHS}
    <path android:strokeColor="{BLUE}" android:strokeWidth="{CURVE_W}" android:strokeLineCap="round"
        android:strokeLineJoin="round" android:pathData="{curve_path()}" />
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
"""

BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{LIGHT}</color>
</resources>
"""

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def draw_glyph(draw, scale, dx=0, dy=0):
    """Draws the icon shapes; scale = pixels per viewport unit."""
    s = lambda x, y: (x * scale + dx, y * scale + dy)  # noqa: E731
    x0, y0, x1, y1, r = BOARD
    draw.rounded_rectangle([*s(x0, y0), *s(x1, y1)], radius=r * scale, fill=INK)
    for x0, y0, x1, y1 in POCKETS:
        draw.rounded_rectangle([*s(x0, y0), *s(x1, y1)], radius=(y1 - y0) / 2 * scale, fill=LIGHT)
    # A round brush moved along the curve: smooth joins and round caps at any width.
    r = CURVE_W * scale / 2
    pts = [s(x, y) for x, y in curve_points()]
    for (xa, ya), (xb, yb) in zip(pts, pts[1:]):
        n = max(1, int(((xb - xa) ** 2 + (yb - ya) ** 2) ** 0.5 / (r / 4)))
        for i in range(n + 1):
            x, y = xa + (xb - xa) * i / n, ya + (yb - ya) * i / n
            draw.ellipse([x - r, y - r, x + r, y + r], fill=BLUE)


def legacy_icon(size, round_icon):
    """Pre-API-26 launcher icon: light square/circle with the glyph, supersampled."""
    big = size * 4
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_icon:
        d.ellipse([0, 0, big - 1, big - 1], fill=LIGHT)
    else:
        d.rounded_rectangle([0, 0, big - 1, big - 1], radius=big // 6, fill=LIGHT)
    # The 108-unit viewport is shown at 72/108 of the icon (adaptive-icon crop).
    scale = big / 72
    draw_glyph(d, scale, dx=-18 * scale, dy=-18 * scale)
    return img.resize((size, size), Image.LANCZOS)


def splash(width, height):
    img = Image.new("RGB", (width * 2, height * 2), DARK)
    d = ImageDraw.Draw(img)
    side = min(width, height) * 0.35 * 2
    left, top = (width * 2 - side) / 2, (height * 2 - side) / 2
    d.rounded_rectangle([left, top, left + side, top + side], radius=side / 5, fill=LIGHT)
    scale = side / 72
    draw_glyph(d, scale, dx=left - 18 * scale, dy=top - 18 * scale)
    return img.resize((width, height), Image.LANCZOS)


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


# Capacitor template icon files that would shadow ours (drawable-v24 wins on API 24+).
TEMPLATE_LEFTOVERS = ["drawable-v24/ic_launcher_foreground.xml", "drawable/ic_launcher_background.xml"]


def main():
    for leftover in TEMPLATE_LEFTOVERS:
        path = os.path.join(RES, leftover)
        if os.path.exists(path):
            os.remove(path)
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), VECTOR)
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        write(os.path.join(RES, "mipmap-anydpi-v26", name), ADAPTIVE)
    write(os.path.join(RES, "values", "ic_launcher_background.xml"), BACKGROUND)
    for density, size in DENSITIES.items():
        folder = os.path.join(RES, f"mipmap-{density}")
        legacy_icon(size, False).save(os.path.join(folder, "ic_launcher.png"))
        legacy_icon(size, True).save(os.path.join(folder, "ic_launcher_round.png"))
        # The PNG foregrounds are replaced by the vector drawable.
        fg = os.path.join(folder, "ic_launcher_foreground.png")
        if os.path.exists(fg):
            os.remove(fg)
    for folder in sorted(os.listdir(RES)):
        path = os.path.join(RES, folder, "splash.png")
        if folder.startswith("drawable") and os.path.exists(path):
            with Image.open(path) as old:
                size = old.size
            splash(*size).save(path)
    print("icons and splash screens written to", os.path.relpath(RES, ROOT))


if __name__ == "__main__":
    main()
